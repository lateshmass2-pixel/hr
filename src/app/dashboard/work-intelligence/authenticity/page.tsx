import { getSession } from '@/lib/auth/session'
import { createClient } from '@/lib/supabase/server'
import { redirect } from 'next/navigation'
import { Card } from '@/components/ui/card'
import { Badge } from '@/components/ui/badge'
import { WorkIntelligenceNav } from '../nav'
import { ShieldCheck } from 'lucide-react'
import { isRoleAtLeast } from '@/lib/rbac/types'

// =============================================================================
// Work Authenticity — /dashboard/work-intelligence/authenticity
// =============================================================================
// Status board of daily reports (spec §18 §6): VERIFIED / REVIEW_REQUIRED /
// UNUSUAL_ACTIVITY / INSUFFICIENT_EVIDENCE, each with its evidence-backed
// reason. Never a percentage, never an accusation.
// =============================================================================

const STATUS_STYLES: Record<string, string> = {
    VERIFIED: 'bg-emerald-100 text-emerald-800',
    REVIEW_REQUIRED: 'bg-amber-100 text-amber-800',
    UNUSUAL_ACTIVITY: 'bg-orange-100 text-orange-800',
    INSUFFICIENT_EVIDENCE: 'bg-gray-100 text-gray-600',
}

export default async function AuthenticityPage() {
    const session = await getSession()
    if (!session) redirect('/login')

    const supabase = await createClient()
    const isManager = isRoleAtLeast(session.role, 'manager')
    if (!isManager) redirect('/dashboard/work-intelligence/git-activity')

    let query = supabase
        .from('daily_work_reports')
        .select(`
            id, employee_id, report_date, authenticity_status, status_reason,
            commit_count, pr_count, review_count, ci_run_count,
            org_employees ( full_name )
        `)
        .eq('organization_id', session.organizationId)
        .order('report_date', { ascending: false })
        .limit(60)

    if (!isManager) {
        const { data: myEmployee } = await supabase
            .from('org_employees')
            .select('id')
            .eq('organization_id', session.organizationId)
            .eq('user_id', session.userId)
            .maybeSingle()
        query = myEmployee
            ? query.eq('employee_id', myEmployee.id)
            : query.eq('employee_id', '00000000-0000-0000-0000-000000000000')
    }

    const { data: reports } = await query

    return (
        <div className="p-6 max-w-5xl mx-auto space-y-6">
            <div className="flex flex-wrap items-center justify-between gap-3">
                <h1 className="text-2xl font-bold text-[#0a3b2a] flex items-center gap-2">
                    <ShieldCheck className="h-6 w-6" /> Work Authenticity
                </h1>
                <WorkIntelligenceNav />
            </div>

            <p className="text-sm text-[#14532d]/70 -mt-2">
                Each status is derived from recorded evidence and explains itself. Statuses are
                review signals — HEMS does not accuse and cannot determine who physically
                typed any line of code.
            </p>

            <Card className="p-6">
                {!reports || reports.length === 0 ? (
                    <p className="text-sm text-slate-500 py-4">
                        No authenticity reports yet. Reports are generated by the scheduled
                        sync (or on demand via the daily report API).
                    </p>
                ) : (
                    <ul className="divide-y divide-slate-50">
                        {(reports as Array<{
                            id: string
                            employee_id: string
                            report_date: string
                            authenticity_status: string
                            status_reason: string | null
                            commit_count: number
                            pr_count: number
                            review_count: number
                            ci_run_count: number
                            org_employees: { full_name: string } | { full_name: string }[] | null
                        }>).map((r) => {
                            const name = Array.isArray(r.org_employees)
                                ? r.org_employees[0]?.full_name ?? 'Unknown'
                                : r.org_employees?.full_name ?? 'Unknown'
                            return (
                                <li key={r.id} className="py-3 space-y-1">
                                    <div className="flex items-center gap-3 flex-wrap">
                                        <span className="font-medium text-[#0a3b2a]">{name}</span>
                                        <span className="text-xs text-slate-400">{r.report_date}</span>
                                        <Badge variant="outline" className={STATUS_STYLES[r.authenticity_status] ?? ''}>
                                            {r.authenticity_status.replaceAll('_', ' ')}
                                        </Badge>
                                        <span className="text-xs text-slate-500">
                                            {r.commit_count} commits · {r.pr_count} PRs · {r.review_count} reviews · {r.ci_run_count} CI runs
                                        </span>
                                    </div>
                                    {r.status_reason && (
                                        <p className="text-sm text-slate-600">Reason: {r.status_reason}</p>
                                    )}
                                </li>
                            )
                        })}
                    </ul>
                )}
            </Card>
        </div>
    )
}
